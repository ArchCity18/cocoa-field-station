ALTER TABLE public.auth_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.blocked_auth_identities ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inputer_invites ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.field_plots ENABLE ROW LEVEL SECURITY;
